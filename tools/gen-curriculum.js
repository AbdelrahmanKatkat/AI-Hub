// Generates assets/curriculum-math.js from curriculum/mathematics.md (the single source of truth).
// Run: node tools/gen-curriculum.js
const fs = require('fs');
const BAR = '¦'; // placeholder for an escaped pipe inside a table cell
const md = fs.readFileSync(__dirname + '/../curriculum/mathematics.md', 'utf8').replace(/\\\|/g, BAR);
const mods = [];
let cur = null;
for (const line of md.split('\n')) {
  const m = /^## Module (\d+) · (.+?)\s+\(`(.+?)`\)/.exec(line);
  if (m) { cur = { n: +m[1], title: m[2], href: m[3], lessons: [] }; mods.push(cur); continue; }
  if (cur && line.startsWith('| ') && !/^\| (id|---)/.test(line)) {
    const c = line.split('|').slice(1, -1).map((s) => s.trim().split(BAR).join('|'));
    if (c.length === 4) cur.lessons.push({ id: c[0], t: c[1], k: (c[2] + " " + c[3]).replace(/[*`]/g, '') });
  }
}
fs.writeFileSync(__dirname + '/../assets/curriculum-math.js',
  '/* GENERATED by tools/gen-curriculum.js from curriculum/mathematics.md - do not edit by hand. */\n' +
  'window.MATH_MODULES = ' + JSON.stringify(mods, null, 1) + ';\n');
console.log(mods.map((m) => m.n + ':' + m.lessons.length).join(' '), 'total', mods.reduce((s, m) => s + m.lessons.length, 0));
