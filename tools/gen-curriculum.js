// Generates assets/curriculum-<slug>.js from curriculum/<file>.md (the single source of truth).
// Usage: node tools/gen-curriculum.js [slug]        slug defaults to "math"
//   math -> curriculum/mathematics.md -> window.MATH_MODULES
//   cv   -> curriculum/computer-vision.md -> window.CV_MODULES
const fs = require('fs');
const FILES = { math: 'mathematics', cv: 'computer-vision' };
const slugs = process.argv[2] ? [process.argv[2]] : Object.keys(FILES);
const BAR = '¦'; // placeholder for an escaped pipe inside a table cell

for (const slug of slugs) {
  const file = FILES[slug] || slug;
  const md = fs.readFileSync(__dirname + `/../curriculum/${file}.md`, 'utf8').replace(/\\\|/g, BAR);
  const mods = [];
  let cur = null;
  for (const line of md.split('\n')) {
    const m = /^## Module (\d+) · (.+?)\s+\(`(.+?)`\)/.exec(line);
    if (m) { cur = { n: +m[1], title: m[2], href: m[3], lessons: [] }; mods.push(cur); continue; }
    if (cur && line.startsWith('| ') && !/^\| (id|---)/.test(line)) {
      const c = line.split('|').slice(1, -1).map((s) => s.trim().split(BAR).join('|'));
      if (c.length === 4) cur.lessons.push({ id: c[0], t: c[1], k: (c[2] + ' ' + c[3]).replace(/[*`]/g, '') });
    }
  }
  fs.writeFileSync(__dirname + `/../assets/curriculum-${slug}.js`,
    `/* GENERATED by tools/gen-curriculum.js from curriculum/${file}.md - do not edit by hand. */\n` +
    `window.${slug.toUpperCase()}_MODULES = ` + JSON.stringify(mods, null, 1) + ';\n');
  console.log(slug, mods.map((m) => m.n + ':' + m.lessons.length).join(' '), 'total', mods.reduce((s, m) => s + m.lessons.length, 0));
}
